// =============================================================================
// assembly.hpp
// -----------------------------------------------------------------------------
// Сборка глобальной матрицы жёсткости K и вектора правой части F по сетке,
// материалу и граничным условиям.
//
// Реализует формулы 1.21, 1.23, 1.25, 1.27, 1.28 пояснительной записки.
// Соответствует разделу 3.1.3.
// =============================================================================

#ifndef FEM_CORE_ASSEMBLY_HPP
#define FEM_CORE_ASSEMBLY_HPP

#include "mesh.hpp"
#include "sparse.hpp"

#include <cstdint>
#include <vector>

namespace fem {

// -----------------------------------------------------------------------------
// Тип граничного условия на одной грани тела.
// -----------------------------------------------------------------------------
enum BCType : std::int32_t {
    BC_NONE      = 0, // условие не задано (трактуется как Нейман с q0 = 0)
    BC_DIRICHLET = 1, // T = T0
    BC_NEUMANN   = 2, // -lambda dT/dn = q0
    BC_ROBIN     = 3  // -lambda dT/dn = alpha (T - T_inf)
};

// -----------------------------------------------------------------------------
// Параметры граничного условия на одной грани.
// Поля используются в зависимости от type.
// -----------------------------------------------------------------------------
struct BoundaryCondition {
    std::int32_t type = BC_NONE;
    double T0    = 0.0;   // для Dirichlet
    double q0    = 0.0;   // для Neumann
    double alpha = 0.0;   // для Robin
    double T_inf = 0.0;   // для Robin
};

// -----------------------------------------------------------------------------
// Локальные источники тепла (раздел 3.3.11 ПЗ).
// -----------------------------------------------------------------------------
struct PointSource {
    std::int32_t node_idx;   // глобальный индекс узла
    double       power;      // P, Вт; знак: + нагрев, − отвод
};

enum VolumeSourceShape : std::int32_t {
    VOLSRC_BOX    = 0,
    VOLSRC_SPHERE = 1,
};

struct VolumeSource {
    std::int32_t shape;      // VOLSRC_BOX | VOLSRC_SPHERE
    double       params[6];  // box: xmin,ymin,zmin,xmax,ymax,zmax
                             // sphere: cx,cy,cz,r,0,0
    double       Q0;         // плотность мощности, Вт/м³
};

// -----------------------------------------------------------------------------
// Полное описание физических параметров задачи и граничных условий.
// Один материал на всю область + по одному ГУ на каждую из 6 граней +
// произвольные списки точечных и объёмных локальных источников.
// -----------------------------------------------------------------------------
struct ProblemSpec {
    double lambda = 1.0;  // коэффициент теплопроводности (Вт/(м·К))
    double Q      = 0.0;  // объёмная плотность мощности по всей области (Вт/м³)
    BoundaryCondition bc[FACE_COUNT];

    std::vector<PointSource>  point_sources;
    std::vector<VolumeSource> volume_sources;

    // Поузельные переопределения значений Дирихле (раздел 3.4.3 ПЗ).
    // Параллельные массивы: dirichlet_node_overrides[i] = индекс узла,
    //                       dirichlet_value_overrides[i] = значение T в нём.
    // Если узел указан здесь, значение из этого массива побеждает любые
    // значения, заданные через bc[].T0.
    std::vector<std::int32_t> dirichlet_node_overrides;
    std::vector<double>       dirichlet_value_overrides;
};

// -----------------------------------------------------------------------------
// Построение шаблона разреженности матрицы (первый проход сборки).
// -----------------------------------------------------------------------------
void build_sparsity_pattern(const Mesh& mesh, CSRMatrix& K);

// -----------------------------------------------------------------------------
// Сборка матрицы K и вектора F (второй проход).
// Учитывает условия Неймана и Робена в цикле по граничным граням; условие
// Дирихле здесь НЕ применяется — оно накладывается отдельной функцией
// после сборки, чтобы сохранить симметрию через модификацию строк/столбцов.
// -----------------------------------------------------------------------------
void assemble(const Mesh& mesh, const ProblemSpec& spec,
              CSRMatrix& K, std::vector<double>& F);

// -----------------------------------------------------------------------------
// Применение условий Дирихле к собранной системе (формулы 1.30–1.31).
// На выходе — список индексов узлов, которые были закреплены, и значения
// в них (используются также для верификации).
// -----------------------------------------------------------------------------
void apply_dirichlet(const Mesh& mesh, const ProblemSpec& spec,
                     CSRMatrix& K, std::vector<double>& F,
                     std::vector<std::int32_t>& dirichlet_nodes,
                     std::vector<double>& dirichlet_values);

} // namespace fem

#endif // FEM_CORE_ASSEMBLY_HPP
