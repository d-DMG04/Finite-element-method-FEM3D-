// =============================================================================
// solver.hpp
// -----------------------------------------------------------------------------
// Метод сопряжённых градиентов (CG) с диагональным предобусловливанием Якоби.
//
// Применяется к симметричной положительно определённой системе K T = F.
// Реализует алгоритм раздела 1.2.9 пояснительной записки.
// Соответствует разделу 3.1.4.
// =============================================================================

#ifndef FEM_CORE_SOLVER_HPP
#define FEM_CORE_SOLVER_HPP

#include "sparse.hpp"

#include <atomic>
#include <cstdint>
#include <functional>
#include <vector>

namespace fem {

// -----------------------------------------------------------------------------
// Параметры запуска решателя.
// -----------------------------------------------------------------------------
struct SolverOptions {
    double       tol_rel  = 1e-8;   // относительная норма невязки
    std::int32_t max_iter = 5000;   // верхний лимит итераций

    // Callback прогресса: вызывается каждые N итераций (см. реализацию).
    // Аргументы: текущая итерация, относительная невязка |r_k|/|F|.
    // Возврат true — продолжать, false — прервать решение.
    // Если callback не задан, проверка прерывания не выполняется.
    std::function<bool(std::int32_t, double)> progress_callback;

    // Период вызова callback (в итерациях). 0 → не вызывать.
    std::int32_t progress_period = 10;
};

// -----------------------------------------------------------------------------
// Диагностика результата решения.
// -----------------------------------------------------------------------------
struct SolverResult {
    std::int32_t iterations    = 0;     // фактическое число итераций
    double       final_residual = 0.0;  // |r_k| / |F|
    double       solve_time_s  = 0.0;   // время решения в секундах
    std::int32_t converged     = 0;     // 1 — критерий достигнут, 0 — нет
    std::int32_t cancelled     = 0;     // 1 — прервано через callback
};

// -----------------------------------------------------------------------------
// Запуск CG с предобусловливателем Якоби.
//
// На вход:
//   K        — собранная разреженная матрица (с применёнными ГУ Дирихле);
//   F        — вектор правой части;
//   opts     — параметры (точность, max_iter);
// На выход:
//   T        — приближённое решение (размер K.size());
//   result   — заполненная диагностика.
//
// Возвращает 1 при достижении критерия точности, 0 при отказе сходимости
// (текущее приближение всё равно записывается в T).
// -----------------------------------------------------------------------------
std::int32_t solve_cg(const CSRMatrix& K,
                      const std::vector<double>& F,
                      const SolverOptions& opts,
                      std::vector<double>& T,
                      SolverResult& result);

} // namespace fem

#endif // FEM_CORE_SOLVER_HPP
